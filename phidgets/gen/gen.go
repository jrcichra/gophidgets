type gen struct {
	b     *bytes.Buffer
	cls   string // PhidgetDCMotor
	bools map[string]bool
	enums map[string]bool
	used  map[string]bool
	cbs   map[string]string
}

func (g *gen) pf(format string, a ...any) { fmt.Fprintf(g.b, format, a...) }

// goType returns the Go type, C type and conversions for a scalar or enum C type.
func (g *gen) goType(c, prop string) (goT, cT, toC, fromC string, ok bool) {
	if s, found := scalars[c]; found {
		if c == "int" && g.bools[prop] {
			return "bool", "C.int", "boolToCInt(%s)", "%s != 0", true
		}
		return s.goT, s.cT, s.cT + "(%s)", s.goT + "(%s)", true
	}
	if g.enums[c] {
		g.used[c] = true
		return "int", "C." + c, "C." + c + "(%s)", "int(%s)", true
	}
	return
}

func (g *gen) class(fns []fn) {
	c, t := g.cls, g.cls
	g.pf("// Code generated by gen/main.go; DO NOT EDIT.\n\npackage phidgets\n\n/*\n#include <phidget22.h>\n#include \"phidgets.h\"\n*/\nimport \"C\"\nimport \"unsafe\"\n\n")
	g.pf("// %s wraps a %s channel.\ntype %s struct {\n\tphidget\n\thandle C.%sHandle\n}\n\n", t, c, t, c)
	g.pf("// Create creates a %s handle.\nfunc (p *%s) Create() {\n\tC.%s_create(&p.handle)\n\tp.rawHandle(unsafe.Pointer(p.handle))\n}\n\n", t, t, c)
	g.pf("// Close closes the handle and deletes it.\nfunc (p *%s) Close() error {\n\tif err := p.phidget.Close(); err != nil {\n\t\treturn err\n\t}\n\treturn p.phidgetError(C.%s_delete(&p.handle))\n}\n\n", t, c)
	var skipped []string
	for _, f := range fns {
		if f.name == "create" || f.name == "delete" || strings.Contains(f.name, "_") {
			continue
		}
		if !g.method(f) {
			skipped = append(skipped, f.name)
		}
	}
	if len(skipped) > 0 {
		fmt.Fprintf(os.Stderr, "%s: skipped %s\n", c, strings.Join(skipped, " "))
	}
}

func (g *gen) method(f fn) bool {
	c, t, name := g.cls, g.cls, upper(f.name)
	cfn := fmt.Sprintf("C.%s_%s", c, f.name)
	switch {
	case strings.HasPrefix(f.name, "setOn") && strings.HasSuffix(f.name, "Handler"):
		return g.handler(f, name, cfn)
	case strings.HasPrefix(f.name, "get") && len(f.params) == 1:
		prop, p := f.name[3:], f.params[0]
		var helper, cT, goT string
		switch {
		case p.typ == "double[3]":
			g.pf("// %s wraps %s_%s.\nfunc (p *%s) %s() ([]float64, error) {\n\treturn getVec3(&p.phidget, func(r *[3]C.double) C.PhidgetReturnCode { return %s(p.handle, r) })\n}\n\n", name, c, f.name, t, name, cfn)
			return true
		case strings.HasSuffix(p.typ, "*"):
			var fromC string
			var ok bool
			goT, cT, _, fromC, ok = g.goType(strings.TrimSuffix(p.typ, "*"), prop)
			if !ok {
				return false
			}
			if s, plain := scalars[strings.TrimSuffix(p.typ, "*")]; plain && (goT == s.goT || goT == "bool") {
				helper = s.get
				if goT == "bool" {
					helper = "getBool"
				}
				g.pf("// %s wraps %s_%s.\nfunc (p *%s) %s() (%s, error) {\n\treturn %s(&p.phidget, func(r *%s) C.PhidgetReturnCode { return %s(p.handle, r) })\n}\n\n", name, c, f.name, t, name, goT, helper, cT, cfn)
				return true
			}
			g.pf("// %s wraps %s_%s.\nfunc (p *%s) %s() (%s, error) {\n\treturn get(&p.phidget, func(r *%s) C.PhidgetReturnCode { return %s(p.handle, r) }, func(r %s) %s { return %s })\n}\n\n", name, c, f.name, t, name, goT, cT, cfn, cT, goT, fmt.Sprintf(fromC, "r"))
			return true
		}
		return false
	}
	// setters and other verbs: every parameter must be a scalar or enum passed by value
	var args, call []string
	for _, p := range f.params {
		goT, _, toC, _, ok := g.goType(p.typ, name[3:])
		if !ok || strings.HasSuffix(p.typ, "*") {
			return false
		}
		args = append(args, goName(p.name)+" "+goT)
		call = append(call, fmt.Sprintf(toC, goName(p.name)))
	}
	if strings.HasPrefix(f.name, "set") {
		if len(f.params) != 1 {
			return false
		}
	}
	rest := ""
	if len(call) > 0 {
		rest = ", " + strings.Join(call, ", ")
	}
	g.pf("// %s wraps %s_%s.\nfunc (p *%s) %s(%s) error {\n\treturn p.phidgetError(%s(p.handle%s))\n}\n\n", name, c, f.name, t, name, strings.Join(args, ", "), cfn, rest)
	return true
}

func (g *gen) handler(f fn, name, cfn string) bool {
	raw, ok := g.cbs[f.params[0].typ]
	if !ok {
		return false
	}
	var types []string
	for _, p := range parseParams(raw) {
		if p.name != "ctx" {
			types = append(types, p.typ)
		}
	}
	cb, ok := callbacks[strings.Join(types, ",")]
	if !ok {
		return false
	}
	g.pf("// %s wraps %s_%s. The handler runs on a C thread.\nfunc (p *%s) %s(f %s) error {\n\treturn p.phidgetError(%s(p.handle, (C.phidget_%s_fcn)(unsafe.Pointer(C.%s)), p.save(f)))\n}\n\n", name, g.cls, f.name, g.cls, name, cb.goT, cfn, cb.typ, cb.shim)
	return true
}

func writeEnum(b *bytes.Buffer, typedef string, vals [][]string) {
	// PhidgetRCServo_Voltage -> RCServoVoltage, PhidgetVoltageOutput_VoltageOutputRange -> VoltageOutputRange
	cls, goName, _ := strings.Cut(strings.TrimPrefix(typedef, "Phidget"), "_")
	if !strings.HasPrefix(goName, cls) {
		goName = cls + goName
	}
	var names []string
	for _, v := range vals {
		names = append(names, v[1])
	}
	prefix := names[0]
	for _, n := range names {
		for !strings.HasPrefix(n, prefix) {
			prefix = prefix[:len(prefix)-1]
		}
	}
	if i := strings.LastIndex(prefix, "_"); i >= 0 {
		prefix = prefix[:i+1]
	} else {
		prefix = ""
	}
	fmt.Fprintf(b, "\n// %s values.\nconst (\n", goName)
	for _, n := range names {
		fmt.Fprintf(b, "\t%s%s = C.%s\n", strings.ReplaceAll(goName, "_", ""), camel(strings.TrimPrefix(n, prefix)), n)
	}
	b.WriteString(")\n")
}

func camel(s string) string {
	var out string
	for _, w := range strings.Split(s, "_") {
		if w == "" {
			continue
		}
		if strings.ContainsAny(w, "0123456789") {
			out += w
		} else {
			out += upper(strings.ToLower(w))
		}
	}
	return out
}
